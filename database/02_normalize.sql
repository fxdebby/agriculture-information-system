-- 5. AUDIT COLUMNS + VALIDATION TRIGGERS -----------------------------
do $$ declare t text; begin
  foreach t in array array['farmer','farm','crop','planting','harvest'] loop
    execute format('alter table %I add column created_at timestamptz not null default now(), add column updated_at timestamptz not null default now(), add column created_by uuid references auth.users(id) on delete set null, add column updated_by uuid references auth.users(id) on delete set null', t);
  end loop;
end $$;

create function set_audit_fields() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now(); new.updated_at := now();
    new.created_by := coalesce(new.created_by, auth.uid()); new.updated_by := auth.uid();
  else
    new.created_at := old.created_at; new.created_by := old.created_by;
    new.updated_at := now(); new.updated_by := auth.uid();
  end if;
  return new;
end $$;
create trigger trg_audit_farmer   before insert or update on farmer   for each row execute function set_audit_fields();
create trigger trg_audit_farm     before insert or update on farm     for each row execute function set_audit_fields();
create trigger trg_audit_crop     before insert or update on crop     for each row execute function set_audit_fields();
create trigger trg_audit_planting before insert or update on planting for each row execute function set_audit_fields();
create trigger trg_audit_harvest  before insert or update on harvest  for each row execute function set_audit_fields();

create function validate_planting() returns trigger language plpgsql as $$
declare v_area numeric;
begin
  select area_hectares into v_area from farm where farm_id = new.farm_id;
  if new.area_planted > v_area then
    raise exception 'Area planted (% ha) cannot exceed the farm area (% ha).', new.area_planted, v_area using errcode = 'check_violation';
  end if;
  return new;
end $$;
create trigger trg_validate_planting before insert or update on planting for each row execute function validate_planting();

create function validate_harvest() returns trigger language plpgsql as $$
declare v_planted date;
begin
  select planting_date into v_planted from planting where planting_id = new.planting_id;
  if new.harvest_date < v_planted then
    raise exception 'Harvest date (%) cannot be earlier than the planting date (%).', new.harvest_date, v_planted using errcode = 'check_violation';
  end if;
  return new;
end $$;
create trigger trg_validate_harvest before insert or update on harvest for each row execute function validate_harvest();

-- 6. PROFILES + ROLES (passwords live only in Supabase Auth, as salted hashes)
create table profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text, email text,
  role_id integer not null default 2 references ref_user_role(role_id),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now());

create function handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name, role_id)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email,'@',1)), 2);
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function handle_new_user();

create function is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role_id = 1); $$;

-- 7. VIEWS (JOINs used by lists, dashboard and reports; RLS still applies) --
create view v_farmer_details with (security_invoker = true) as
select f.farmer_id, f.first_name, f.last_name, f.first_name||' '||f.last_name as farmer_name,
       f.contact_number, f.municipality_id, m.municipality_name,
       m.municipality_name||', '||p.province_name as address, f.date_registered
from farmer f join ref_city_municipality m on m.municipality_id=f.municipality_id
              join ref_province p on p.province_id=m.province_id;

create view v_farm_details with (security_invoker = true) as
select f.farm_id, f.farm_name, f.farmer_id, fr.first_name||' '||fr.last_name as farmer_name,
       f.municipality_id, m.municipality_name||', '||p.province_name as location,
       f.area_hectares, f.soil_type_id, s.soil_type_description as soil_type,
       f.irrigation_type_id, i.irrigation_type_description as irrigation_type
from farm f join farmer fr on fr.farmer_id=f.farmer_id
            join ref_city_municipality m on m.municipality_id=f.municipality_id
            join ref_province p on p.province_id=m.province_id
            join ref_soil_type s on s.soil_type_id=f.soil_type_id
            join ref_irrigation_type i on i.irrigation_type_id=f.irrigation_type_id;

create view v_crop_details with (security_invoker = true) as
select c.crop_id, c.crop_name, c.variety, c.category_id, cc.category_description as crop_category,
       c.growing_period_days, c.season_id, s.season_description as recommended_season
from crop c join ref_crop_category cc on cc.category_id=c.category_id
            join ref_season s on s.season_id=c.season_id;

create view v_planting_details with (security_invoker = true) as
select p.planting_id, p.planting_date, p.expected_harvest_date, p.area_planted, p.seed_quantity,
       p.farm_id, f.farm_name, f.farmer_id, fr.first_name||' '||fr.last_name as farmer_name,
       p.crop_id, c.crop_name, c.variety, p.status_id, ps.status_description as status
from planting p join farm f on f.farm_id=p.farm_id
                join farmer fr on fr.farmer_id=f.farmer_id
                join crop c on c.crop_id=p.crop_id
                join ref_planting_status ps on ps.status_id=p.status_id;

create view v_harvest_details with (security_invoker = true) as
select h.harvest_id, h.harvest_date, h.quantity_kg, h.selling_price_per_kg,
       round(h.quantity_kg*h.selling_price_per_kg,2) as estimated_value,
       h.planting_id, f.farm_id, f.farm_name, fr.first_name||' '||fr.last_name as farmer_name,
       c.crop_id, c.crop_name, c.variety,
       h.quality_grade_id, g.grade_description as quality_grade,
       h.remark_id, r.remark_description as remarks
from harvest h join planting p on p.planting_id=h.planting_id
               join farm f on f.farm_id=p.farm_id
               join farmer fr on fr.farmer_id=f.farmer_id
               join crop c on c.crop_id=p.crop_id
               join ref_quality_grade g on g.grade_id=h.quality_grade_id
               join ref_harvest_remark r on r.remark_id=h.remark_id;

create view v_farmers_farms with (security_invoker = true) as
select fr.farmer_id, fr.first_name||' '||fr.last_name as farmer_name,
       m.municipality_name||', '||p.province_name as farmer_address,
       f.farm_id, f.farm_name, fm.municipality_name as farm_city, f.area_hectares, i.irrigation_type_description as irrigation_type
from farmer fr join ref_city_municipality m on m.municipality_id=fr.municipality_id
               join ref_province p on p.province_id=m.province_id
               left join farm f on f.farmer_id=fr.farmer_id
               left join ref_city_municipality fm on fm.municipality_id=f.municipality_id
               left join ref_irrigation_type i on i.irrigation_type_id=f.irrigation_type_id;

create view v_crops_per_farm with (security_invoker = true) as
select f.farm_id, f.farm_name, c.crop_id, c.crop_name, c.variety,
       count(p.planting_id) as planting_count, sum(p.area_planted) as total_area_planted,
       min(p.planting_date) as first_planting_date, max(p.planting_date) as last_planting_date
from planting p join farm f on f.farm_id=p.farm_id join crop c on c.crop_id=p.crop_id
group by f.farm_id, f.farm_name, c.crop_id, c.crop_name, c.variety;

create view v_planting_by_status with (security_invoker = true) as
select ps.status_id, ps.status_description as status, count(p.planting_id) as total
from ref_planting_status ps left join planting p on p.status_id=ps.status_id
group by ps.status_id, ps.status_description order by ps.status_id;

create view v_dashboard_summary with (security_invoker = true) as
select (select count(*) from farmer) as total_farmers, (select count(*) from farm) as total_farms,
       (select count(*) from crop) as total_crops, (select count(*) from planting) as total_plantings,
       (select count(*) from harvest) as total_harvests,
       (select coalesce(sum(quantity_kg),0) from harvest) as total_harvested_kg,
       (select coalesce(sum(quantity_kg*selling_price_per_kg),0) from harvest) as total_estimated_value;

-- 8. ROW LEVEL SECURITY ----------------------------------------------
-- Admin: everything.  Staff: read all; add + edit farmers, farms, plantings, harvests.
-- Crops and lookup tables: everyone reads, only Admin writes.  Not signed in: nothing.
do $$ declare t text; begin
  foreach t in array array['farmer','farm','planting','harvest'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy "%1$s_select" on %1$I for select to authenticated using (true)', t);
    execute format('create policy "%1$s_insert" on %1$I for insert to authenticated with check (true)', t);
    execute format('create policy "%1$s_update" on %1$I for update to authenticated using (true) with check (true)', t);
    execute format('create policy "%1$s_delete" on %1$I for delete to authenticated using (is_admin())', t);
  end loop;
  foreach t in array array['crop','ref_user_role','ref_province','ref_city_municipality','ref_crop_category','ref_season',
                           'ref_soil_type','ref_irrigation_type','ref_planting_status','ref_quality_grade','ref_harvest_remark'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy "%1$s_select" on %1$I for select to authenticated using (true)', t);
    execute format('create policy "%1$s_write"  on %1$I for all    to authenticated using (is_admin()) with check (is_admin())', t);
  end loop;
end $$;
alter table profiles enable row level security;
create policy "profiles_select" on profiles for select to authenticated using (id = auth.uid() or is_admin());
create policy "profiles_update" on profiles for update to authenticated using (is_admin()) with check (is_admin());
create policy "profiles_delete" on profiles for delete to authenticated using (is_admin());

