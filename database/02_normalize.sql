--  Converts the instructor's five starting tables (farmer, farm, crop,
--  planting, harvest) to Third Normal Form IN PLACE, keeping all rows.
--
--  Run once, after 01_original_tables.sql (or on your own loaded copy).
--  To start over, run 01_original_tables.sql again, then this file.
--
--    1. Guard
--    2. Lookup tables (seeded, then completed from the existing data)
--    3. Normalize each core table (add ID column > fill > drop text column)
--    4. Constraints
