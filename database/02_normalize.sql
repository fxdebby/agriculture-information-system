-- Replace the original foreign keys (whatever they are named) with named ones below.
do $$ declare r record; begin
  for r in select conrelid::regclass as t, conname from pg_constraint
           where contype='f' and conrelid in ('farm'::regclass,'planting'::regclass,'harvest'::regclass)
  loop execute format('alter table %s drop constraint %I', r.t, r.conname); end loop;
end $$;

