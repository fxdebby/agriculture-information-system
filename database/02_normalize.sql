-- 1. GUARD ------------------------------------------------------------
do $$ begin
  if not exists (select 1 from information_schema.columns
                 where table_schema='public' and table_name='crop' and column_name='crop_category') then
    raise exception 'Already normalized (or the original tables are missing). Run 01_original_tables.sql first.';
  end if;
end $$;

-- 2. LOOKUP TABLES ----------------------------------------------------
create table ref_user_role       (role_id integer primary key, role_description text not null unique);
create table ref_province        (province_id integer generated by default as identity primary key, province_name text not null unique);
create table ref_city_municipality (
    municipality_id   integer generated by default as identity primary key,
    municipality_name text    not null,
    province_id       integer not null references ref_province(province_id),
    constraint uq_municipality unique (municipality_name, province_id));
create table ref_crop_category   (category_id integer generated by default as identity primary key, category_description text not null unique);
create table ref_season          (season_id integer generated by default as identity primary key, season_description text not null unique);
create table ref_soil_type       (soil_type_id integer generated by default as identity primary key, soil_type_description text not null unique);
create table ref_irrigation_type (irrigation_type_id integer generated by default as identity primary key, irrigation_type_description text not null unique);
create table ref_planting_status (status_id integer generated by default as identity primary key, status_description text not null unique);
create table ref_quality_grade   (grade_id integer generated by default as identity primary key, grade_description text not null unique);
create table ref_harvest_remark  (remark_id integer generated by default as identity primary key, remark_description text not null unique);

insert into ref_user_role values (1,'Administrator'),(2,'Staff');

-- Fixed values first (the harvest remarks keep the IDs given in the project brief)
insert into ref_harvest_remark (remark_id, remark_description) overriding system value values
 (1,'Good Harvest'),(2,'Acceptable Quality'),(3,'Low Yield'),(4,'Poor Quality'),(5,'Damaged Harvest'),(6,'High Quality Harvest');
insert into ref_planting_status (status_description) values ('Planted'),('Growing'),('Harvested'),('Failed');
insert into ref_season (season_description) values ('Wet Season'),('Dry Season'),('Year Round');
insert into ref_quality_grade (grade_description) values ('Grade A'),('Grade B'),('Grade C');

-- Then add any value that exists in the data but is not listed yet
insert into ref_crop_category (category_description)
  select distinct on (lower(trim(crop_category))) trim(crop_category) from crop where nullif(trim(crop_category),'') is not null order by lower(trim(crop_category)), 1;
insert into ref_season (season_description)
  select distinct on (lower(trim(recommended_season))) trim(recommended_season) from crop c
  where nullif(trim(recommended_season),'') is not null
    and not exists (select 1 from ref_season s where lower(s.season_description)=lower(trim(c.recommended_season)))
  order by lower(trim(recommended_season)), 1;
insert into ref_soil_type (soil_type_description)
  select distinct on (lower(trim(soil_type))) trim(soil_type) from farm where nullif(trim(soil_type),'') is not null order by lower(trim(soil_type)), 1;
insert into ref_irrigation_type (irrigation_type_description)
  select distinct on (lower(trim(irrigation_type))) trim(irrigation_type) from farm where nullif(trim(irrigation_type),'') is not null order by lower(trim(irrigation_type)), 1;
insert into ref_planting_status (status_description)
  select distinct on (lower(trim(status))) trim(status) from planting p
  where nullif(trim(status),'') is not null
    and not exists (select 1 from ref_planting_status s where lower(s.status_description)=lower(trim(p.status)))
  order by lower(trim(status)), 1;
insert into ref_quality_grade (grade_description)
  select distinct on (lower(trim(quality_grade))) trim(quality_grade) from harvest h
  where nullif(trim(quality_grade),'') is not null
    and not exists (select 1 from ref_quality_grade g where lower(g.grade_description)=lower(trim(h.quality_grade)))
  order by lower(trim(quality_grade)), 1;
insert into ref_harvest_remark (remark_description)
  select distinct on (lower(trim(remarks))) trim(remarks) from harvest h
  where nullif(trim(remarks),'') is not null
    and not exists (select 1 from ref_harvest_remark r where lower(r.remark_description)=lower(trim(h.remarks)))
  order by lower(trim(remarks)), 1;
-- "Good harvest" in the data is the brief's "Good Harvest" (same ID 1), matched ignoring case.

-- Province / city: split "City, Province" addresses (no province given = Cebu)
insert into ref_province (province_name)
  select distinct coalesce(nullif(trim(split_part(a,',',2)),''),'Cebu')
  from (select address a from farmer union select location from farm) x where nullif(trim(a),'') is not null;
insert into ref_city_municipality (municipality_name, province_id)
  select distinct trim(split_part(a,',',1)), p.province_id
  from (select address a from farmer union select location from farm) x
  join ref_province p on lower(p.province_name)=lower(coalesce(nullif(trim(split_part(a,',',2)),''),'Cebu'))
  where nullif(trim(a),'') is not null;

-- 3. NORMALIZE THE CORE TABLES ---------------------------------------
-- crop
alter table crop add column category_id integer, add column season_id integer;
update crop c set category_id = (select category_id from ref_crop_category r where lower(r.category_description)=lower(trim(c.crop_category))),
                  season_id   = (select season_id   from ref_season r        where lower(r.season_description)=lower(trim(c.recommended_season)));
alter table crop drop column crop_category, drop column recommended_season;

-- farmer / farm: one atomic city reference replaces the free-text address / location
alter table farmer add column municipality_id integer;
update farmer f set municipality_id = (select m.municipality_id from ref_city_municipality m join ref_province p using (province_id)
   where lower(m.municipality_name)=lower(trim(split_part(f.address,',',1)))
     and lower(p.province_name)=lower(coalesce(nullif(trim(split_part(f.address,',',2)),''),'Cebu')));
alter table farmer drop column address;

alter table farm add column municipality_id integer, add column soil_type_id integer, add column irrigation_type_id integer;
update farm f set municipality_id = (select m.municipality_id from ref_city_municipality m join ref_province p using (province_id)
   where lower(m.municipality_name)=lower(trim(split_part(f.location,',',1)))
     and lower(p.province_name)=lower(coalesce(nullif(trim(split_part(f.location,',',2)),''),'Cebu'))),
 soil_type_id       = (select soil_type_id from ref_soil_type r where lower(r.soil_type_description)=lower(trim(f.soil_type))),
 irrigation_type_id = (select irrigation_type_id from ref_irrigation_type r where lower(r.irrigation_type_description)=lower(trim(f.irrigation_type)));
alter table farm drop column location, drop column soil_type, drop column irrigation_type;

-- planting
alter table planting add column status_id integer;
update planting p set status_id = (select status_id from ref_planting_status r where lower(r.status_description)=lower(trim(p.status)));
alter table planting drop column status;

-- harvest
alter table harvest add column quality_grade_id integer, add column remark_id integer;
update harvest h set quality_grade_id = (select grade_id  from ref_quality_grade r  where lower(r.grade_description)=lower(trim(h.quality_grade))),
                     remark_id        = (select remark_id from ref_harvest_remark r where lower(r.remark_description)=lower(trim(h.remarks)));
alter table harvest drop column quality_grade, drop column remarks;

